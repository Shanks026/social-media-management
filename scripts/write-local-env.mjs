// Writes .env.development.local (git-ignored) so `npm run dev` talks to the
// local Supabase stack (#91, ADR 0005). Values come from `supabase status`, so
// the stack must be running: `npx supabase start` first.
//
//   npm run env:local
//
// Vite loads .env.development.local only in development mode, so a production
// build (`npm run build`) and `npm run dev:prod` never see these values.

/* global process, console */
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const FILE = '.env.development.local'
const APP_URL = 'http://localhost:5173'

let status
try {
  const out = execSync('npx supabase status -o json', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })
  status = JSON.parse(out.slice(out.indexOf('{')))
} catch (err) {
  console.error('Could not read `supabase status`. Is the local stack running? Try `npx supabase start`.')
  console.error(String(err.stderr || err.message).trim().split('\n').slice(-3).join('\n'))
  process.exit(1)
}

if (!status.API_URL || !status.ANON_KEY) {
  console.error('`supabase status` returned no API_URL / ANON_KEY.')
  process.exit(1)
}

writeFileSync(
  FILE,
  [
    '# Generated by `npm run env:local` from the local Supabase stack. Git-ignored.',
    `VITE_SUPABASE_URL=${status.API_URL}`,
    `VITE_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
    `VITE_APP_URL=${APP_URL}`,
    '',
  ].join('\n'),
)
console.log(`Wrote ${FILE} → ${status.API_URL} (Studio: ${status.STUDIO_URL}, Mailpit: ${status.MAILPIT_URL})`)
